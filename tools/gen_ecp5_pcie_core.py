#!/usr/bin/env python3
"""Generate the ECP5-PCIe core (third_party/ECP5-PCIe) as flat Verilog for LiteX.

Amaranth 0.4 emits RTLIL; the OSS CAD Suite Yosys (tools/bin) writes the Verilog.
"""

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "third_party" / "ECP5-PCIe" / "Gateware"))

from amaranth.back import rtlil
from amaranth.vendor import LatticeECP5Platform

from ecp5_pcie.ecp5_pcie_core import ECP5PCIeCore

from gateware.ecp5pcie.core import VERILOG_DIR, core_name


class _GenPlatform(LatticeECP5Platform):
    # Only used for add_clock_constraint() during elaboration; constraints are not exported.
    device      = "LFE5UM-45F"
    package     = "BG381"
    speed       = "8"
    default_clk = None
    resources   = []
    connectors  = []


def _yosys():
    local = ROOT / "tools" / "bin" / "yosys"
    if local.exists():
        return str(local)
    path = shutil.which("yosys")
    if path is None:
        raise SystemExit("yosys not found; run tools/ensure_fpga_toolchain.sh")
    return path


def _git_describe(path):
    def git(*args):
        return subprocess.run(["git", "-C", str(path), *args], check=True,
                              capture_output=True, text=True).stdout.strip()
    rev   = git("rev-parse", "--short", "HEAD")
    dirty = "-dirty" if git("status", "--porcelain", "--untracked-files=no") else ""
    return f"{rev}{dirty}"


def generate(gen=1, fabric_clk=False, transaction_layer=False, output=None):
    name   = core_name(gen, fabric_clk, transaction_layer)
    output = Path(output) if output else VERILOG_DIR / f"{name}.v"

    core = ECP5PCIeCore(gen=gen, fabric_clk=fabric_clk, transaction_layer=transaction_layer)
    text = rtlil.convert(core, name=name, platform=_GenPlatform(toolchain="Trellis"), ports=core.ports())
    # Yosys rejects cell ports with private "$" ids, which Amaranth 0.4 emits for unnamed
    # Signals crossing a module boundary.
    text = re.sub(r"(?<=\s)\$signal((?:\$\d+)?)\b",
                  lambda m: "\\anon_signal" + m.group(1).replace("$", "_"), text)

    with tempfile.TemporaryDirectory() as tmp:
        il = Path(tmp) / f"{name}.il"
        v  = Path(tmp) / f"{name}.v"
        il.write_text(text)
        subprocess.run([_yosys(), "-q", "-p",
            f"read_verilog -lib +/ecp5/cells_bb.v; read_rtlil {il}; "
            f"hierarchy -check -top {name}; proc; flatten; opt_clean; "
            f"write_verilog {v}"], check=True)
        body = v.read_text()

    header = (
        f"// Generated by tools/gen_ecp5_pcie_core.py -- do not edit.\n"
        f"// ECP5-PCIe {_git_describe(ROOT / 'third_party' / 'ECP5-PCIe')}, "
        f"gen={gen} fabric_clk={fabric_clk} transaction_layer={transaction_layer}\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header + body)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gen", type=int, choices=[1, 2], default=1)
    parser.add_argument("--fabric-clk", action="store_true",
                        help="DCU reference clock from the sync clock instead of EXTREF0")
    parser.add_argument("--transaction-layer", action="store_true",
                        help="Include the ECP5-PCIe config-space responder")
    parser.add_argument("-o", "--output", help="Output file (default: gateware/ecp5pcie/verilog/<name>.v)")
    args = parser.parse_args()
    path = generate(args.gen, args.fabric_clk, args.transaction_layer, args.output)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
